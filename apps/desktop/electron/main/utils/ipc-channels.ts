/**
 * Single source of truth for all IPC channel names in the main process.
 *
 * Two naming spaces coexist:
 *   SEND      — what the renderer sends; what ipcMain listens on
 *   CORE      — what IpcClient emits to tipeline_core (usually = SEND, except exec/run)
 *   CORE_RESP — event name the core emits back; what IpcClient handler is keyed on
 *
 * MessageManager forwards responses to the renderer via ad hoc channels
 * (ipcMain.handle() return values, or `stream:<correlationId>` / `stream:broadcast`
 * pushes) rather than a static RECV mapping — see MessageManager.ts.
 */

